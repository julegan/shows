#!/usr/bin/env node
"use strict";
/* NearHear venue listings are SECONDARY leads only, not authoritative music
 * event records. This script is disconnected from events.js.
 * Every bill requires an original organizer/artist/ticket source to publish.
 */
const fs=require("node:fs");
const path=require("node:path");
const URL="https://nearhear.app/venues/4583";
const REPORT=path.join(__dirname,"../discovery/wyrd-secondary-leads-review.md");
const MAX_BYTES=250000;
const TZ="America/Los_Angeles";
const MAX_DAYS=366;
function safe(s){return String(s||"").replace(/[|\n\r\t]+/g," ").replace(/[<>]/g,"").trim().slice(0,220);}
function sourceUrl(str){
 try{
  const u=new URL(str);
  if(u.protocol!=="https:"||u.username||u.password||u.port||u.href.length>1300)return null;
  const approved=new Set(["www.sadtimesproductions.com","sadtimesproductions.com","shadowhouse.bandcamp.com","www.eventbrite.com","eventbrite.com","www.instagram.com","instagram.com"]);
  if(!approved.has(u.hostname.toLowerCase()))return null;
  return u.origin+u.pathname;
 }catch{return null;}
}
function localTime(iso){
 const d=new Date(iso);
 if(!Number.isFinite(d.getTime())||!/^\d{4}-\d{2}-\d{2}T/.test(iso)||!/(?:Z|[+-]\d\d:\d\d)$/.test(iso))return null;
 const parts=new Intl.DateTimeFormat("en-US",{timeZone:TZ,year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",hourCycle:"h23"}).formatToParts(d);
 const get=key=>parts.find(p=>p.type===key)?.value;
 return get("year")+"-"+get("month")+"-"+get("day")+" "+get("hour")+":"+get("minute")+" "+TZ;
}
function parse(html,now=new Date()){
 if(typeof html!=="string"||html.length>MAX_BYTES)throw Error("NearHear source empty or exceeded size limit");
 const rows=[];
 const scripts=[...html.matchAll(/<script\b[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script\s*>/gi)];
 if(!scripts.length||scripts.length>50)throw Error("No bounded original NearHear structured data; source changed");
 for(const entry of scripts){
  let j;
  try{j=JSON.parse(entry[1]);}catch{continue;}
  for(const x of Array.isArray(j)?j:[j]){
   const type=Array.isArray(x?.["@type"])?x["@type"]:[x?.["@type"]];
   if(!type.some(t=>t==="MusicEvent"))continue;
   const addr=x?.location?.address;
   // NearHear's venue JSON-LD name is blank; require validated ADDRESS.
   const normalized=String(addr?.streetAddress||"").toLowerCase().replace(/[.,]/g," ").replace(/\s+/g," ");
   const region=String(addr?.addressRegion||"").toUpperCase();
   if(!/^4704\s+(?:se|southeast)\s+65th\s+ave(?:nue)?\b/.test(normalized)||
     String(addr?.addressLocality||"").toLowerCase()!=="portland"||
     (region&&region!=="OR"&&region!=="OREGON"))continue;
   const start=String(x.startDate||""),when=localTime(start),d=new Date(start),delta=(d.getTime()-now.getTime())/86400000;
   if(!when||!Number.isFinite(delta)||delta < -1||delta>MAX_DAYS)continue;
   const title=safe(x.name);
   const artists=Array.isArray(x.performer)?x.performer.map(p=>safe(p?.name)).filter(Boolean).slice(0,12):[];
   if(!title||!artists.length)continue;
   const original=sourceUrl(x.offers?.url);
   const generic=!!original&&/sadtimesproductions\.com\/shows\/?$/.test(original);
   rows.push({title,when,originalUtc:start,artists,
    secondaryUrl:URL,promoterLeadUrl:original,promoterSourceKind:generic?"general-promoter-archive-not-event-proof":original?"possible-original-source-unverified":"no-original-source",
    verification:"SECONDARY ONLY: original dated bill, lineup, Wyrd venue and time type required; DO NOT PUBLISH"});
  }
 }
 if(!rows.length)throw Error("No credible future Wyrd music leads in source; may be unavailable, NOT zero shows");
 if(rows.length>40)throw Error("Unexpected NearHear Wyrd lead volume");
 const uniq=new Map();
 for(const row of rows){
  const id=row.originalUtc+"|"+row.title.toLowerCase();
  if(!uniq.has(id))uniq.set(id,row);
 }
 return [...uniq.values()].sort((a,b)=>a.originalUtc.localeCompare(b.originalUtc));
}
function report(rows,error){
 const lines=["# Wyrd Hut — secondary upcoming music leads (review-only)","",
  "Generated by a bounded public NearHear venue HTML inspection. **NearHear is a secondary aggregator, not the Wyrd Hut organizer or original ticket source. These leads are NOT approved SHOWS events.**",
  "Displayed local dates/times are converted from aggregator UTC data to **America/Los_Angeles**. They may describe show, doors, or listing time; **not independently confirmed**. Event sources still require original first-party proof. Wyrd Hut is at 4704 SE 65th Ave (per recent organizer listings); do not confuse it with Wyrd Leather and Mead in Milwaukie.",""];
 if(error){lines.push("**Source hold:** "+safe(error)+". Existing events and editorial priority remain unchanged.","");return lines.join("\n")+"\n";}
 lines.push("**"+rows.length+" distinct future Wyrd music leads found; 0 automatically approved.**","","| Local date / time (unconfirmed) | Bill (secondary) | Original promoter evidence | Next verification |","| --- | --- | --- | --- |");
 for(const x of rows){
  const original=x.promoterLeadUrl&&x.promoterSourceKind!=="general-promoter-archive-not-event-proof"
   ?"[Possible source]("+x.promoterLeadUrl+") — verify exact bill"
   :x.promoterLeadUrl?"General [Sad Times show archive]("+x.promoterLeadUrl+") — **not a dated bill**"
    :"Not present";
  lines.push("| "+safe(x.when)+" | "+safe(x.title)+" | "+original+" | Check **original artist/organizer event flyer**, year, room, doors vs show and ticket status; [secondary listing]("+x.secondaryUrl+") |");
 }
 lines.push("","No source artwork is downloaded or mirrored. Absence in this partial secondary source is not evidence Wyrd has no shows. Confirmed events require a separate reviewed SHOWS PR.","");
 return lines.join("\n")+"\n";
}
async function fetchLeads({request=fetch,now=new Date()}={}){
 const r=await request(URL,{redirect:"error",headers:{Accept:"text/html","User-Agent":"SHOWS-review-only/0.1"},signal:AbortSignal.timeout(15000)});
 if(!r.ok||!String(r.headers.get("content-type")||"").toLowerCase().includes("text/html"))
  throw Error("NearHear venue HTML unavailable HTTP "+r.status);
 const reader=r.body?.getReader();if(!reader)throw Error("NearHear body unreadable");
 const bufs=[];let bytes=0;
 for(;;){
  const {done,value}=await reader.read();if(done)break;bytes+=value.byteLength;
  if(bytes>MAX_BYTES){await reader.cancel();throw Error("NearHear original page exceeds bound");}
  bufs.push(Buffer.from(value));
 }
 return parse(Buffer.concat(bufs).toString("utf8"),now);
}
async function main(){
 let rows=[],error=null;
 try{rows=await fetchLeads();}
 catch(e){error=e.message||String(e);}
 fs.writeFileSync(REPORT,report(rows,error));
 console.log("Wyrd secondary leads: "+rows.length+" candidate leads, 0 approved."+(error?" Source hold: "+error:""));
}
if(require.main===module)main().catch(e=>{console.error(e);process.exitCode=1});
module.exports={URL,MAX_BYTES,sourceUrl,localTime,parse,report,fetchLeads};
