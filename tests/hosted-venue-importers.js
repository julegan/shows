"use strict";
const assert=require("node:assert/strict");
const {parseHostedLinks,parseHostedDetail,safeEventUrl}=require("../scripts/hosted-venue-importers");
const sources=require("../discovery/sources.json").sources;
const r=sources.find(s=>s.id==="roseland"),h=sources.find(s=>s.id==="hawthorne-theatre");
assert(r&&h);
const ros="https://roselandpdx.com/event/basement/roseland-theater/portland-oregon/";
const haw="https://hawthornetheatre.com/event/ho99o9-n8noface-sincerely___-the-void/hawthorne-theatre/portland-oregon/";
assert.equal(safeEventUrl(ros,r),ros);
assert.equal(safeEventUrl("https://evil.example/event/basement/roseland-theater/portland-oregon/",r),null);
assert.equal(safeEventUrl(ros+"?tracking=1",r),null);
assert.equal(safeEventUrl("/event/other/hawthorne-lounge/portland-oregon/",h),null,"Never mislabel Lounge as Theatre");
const listing='<a href="'+ros+'">Basement</a><a href="'+ros+'">Duplicate</a><a href="https://bad.invalid/event/evil/roseland-theater/portland-oregon/">Bad</a>';
assert.deepEqual(parseHostedLinks(listing,r),[ros]);
assert.throws(()=>parseHostedLinks("<p>Calendar layout changed</p>",r),/no first-party event-detail/);
const html='<html><head><script>var date="Saturday, December 5th, 2026 9:00PM";</script></head><body><h1>Basement</h1><p>Wednesday, October 28</p><p>Doors: 6 pm Show: 7 pm</p><section>Wednesday, October 28th, 2026 7:00PM Roseland Theater All Ages</section></body></html>';
const item=parseHostedDetail(html,ros,r);
assert.equal(item.title,"Basement");
assert.equal(item.venue,"Roseland Theater");
assert.equal(item.startDate,"2026-10-29T02:00:00.000Z");
assert.equal(item.fullUrl,ros);
assert.equal(item.artwork,undefined);
assert.match(parseHostedDetail(html.replace("Show: 7 pm","Show: 8 pm"),ros,r).hold,/conflicts/);
assert.match(parseHostedDetail(html.replace("2026 7:00PM","2026"),ros,r).hold,/No explicit year/);
assert.match(parseHostedDetail(html.replace("<h1>Basement</h1>","<h1>MOVED TO ANOTHER VENUE — Basement</h1>"),ros,r).hold,/moved/);
assert.match(parseHostedDetail(html.replace("<h1>Basement</h1>","<h1>VIP UPGRADE (ENTRY TICKET NOT INCLUDED)</h1>"),ros,r).hold,/Ticket add-on/);
const hawDoc='<h1>Ho99o9 &amp; N8NOFACE – Sincerely___ The Void</h1><div>Show: 7:30 pm</div><div>Wednesday, October 28th, 2026 7:30PM Hawthorne Theatre All Ages</div>';
const hItem=parseHostedDetail(hawDoc,haw,h);
assert.equal(hItem.title,"Ho99o9 & N8NOFACE – Sincerely___ The Void");
assert.equal(hItem.venue,"Hawthorne Theatre");
assert.equal(hItem.startDate,"2026-10-29T02:30:00.000Z");
assert.match(parseHostedDetail(hawDoc.replace("Hawthorne Theatre All Ages","Hawthorne Lounge All Ages"),haw,h).hold,/Lounge/);
console.log("PASS — Roseland/Hawthorne official event details, exact showtimes, room identity, moved/VIP exclusion and primary URL restrictions");
