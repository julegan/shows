"use strict";
const assert=require("node:assert/strict");
const {safeWonderUrl,parseWonderLinks,parseWonderDetail}=require("../scripts/wonder-importer");
const src=require("../discovery/sources.json").sources.find(s=>s.id==="wonder-ballroom");
assert(src);
const url="https://wonderballroom.com/event/slift-2/wonder-ballroom/portland-oregon/";
const other="https://wonderballroom.com/event/buzzcocks-tour/wonder-ballroom/portland-oregon/";
assert.equal(safeWonderUrl(url,src),url);
assert.equal(safeWonderUrl("https://evil.invalid/event/slift-2/wonder-ballroom/portland-oregon/",src),null);
assert.equal(safeWonderUrl(url+"?tracking=1",src),null);
assert.equal(safeWonderUrl("/event/something/roseland-theater/portland-oregon/",src),null);
assert.deepEqual(parseWonderLinks('<a href="'+url+'">A</a><a href="'+url+'">Again</a><a href="'+other+'">B</a><a href="https://evil.invalid/event/x/wonder-ballroom/portland-oregon/">Bad</a>',src),[url,other]);
assert.throws(()=>parseWonderLinks("<p>Only scripts, no calendar links</p>",src),/layout requires review/);
const page='<html><head><title>SLIFT I Official Info I Oct 21, 2026 I Wonder Ballroom I Portland</title></head>'+
'<body><h1>SLIFT</h1><h2>Monqui Presents</h2><article>Wednesday, October 21 Doors : 7 pm, Show : 8 pm, all ages</article></body></html>';
const e=parseWonderDetail(page,url,src);
assert.equal(e.title,"SLIFT");
assert.equal(e.venue,"Wonder Ballroom");
assert.equal(e.startDate,"2026-10-22T03:00:00.000Z");
assert.equal(e.artwork,undefined);
assert.match(parseWonderDetail(page.replace("Oct 21, 2026","Oct 21"),url,src).hold,/full dated year/);
assert.match(parseWonderDetail(page.replace("Wednesday, October 21","Tuesday, October 21"),url,src).hold,/weekday/);
assert.match(parseWonderDetail(page.replace("October 21 Doors","October 22 Doors"),url,src).hold,/does not match/);
assert.match(parseWonderDetail(page.replace("Show : 8 pm","Doors : 8 pm"),url,src).hold,/No showtime/);
assert.match(parseWonderDetail(page.replace("<h1>SLIFT</h1>","<h1>MOVED TO ROSELAND THEATER — SLIFT</h1>"),url,src).hold,/Moved/);
assert.match(parseWonderDetail(page.replace("<h1>SLIFT</h1>","<h1>*Postponed* SLIFT</h1>"),url,src).hold,/postponed/);
const future=page.replace("Oct 21, 2026","Feb 9, 2027").replace("Wednesday, October 21","Tuesday, February 9");
assert.equal(parseWonderDetail(future,url,src).startDate,"2027-02-10T04:00:00.000Z");
console.log("PASS — Wonder Ballroom exact primary URL, title-year and weekday cross-check, showtime, DST and moved bill holds");
