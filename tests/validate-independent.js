const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','events.js'),'utf8'),ctx);
const events=ctx.window.SHOWS_EVENTS,meta=ctx.window.SHOWS_DATASET;
const added=events.filter(e=>e.addedIn==='2026-10-17-independent-venues');
assert.equal(added.length,27,'27 genuinely new independent-venue bills');
assert(meta.totalOccurrences>=182);
assert(meta.musicOccurrences>=128);
assert((meta.batchId==='2026-10-17-independent-venues'&&meta.addedOccurrences===27)||meta.previousBatches.some(b=>b.batchId==='2026-10-17-independent-venues'&&b.addedOccurrences===27));
assert(added.length===27);
for(const [venue,n] of [['No Fun',16],['Twilight Cafe and Bar',10],['Kenton Club',1]])
 assert.equal(added.filter(e=>e.venue===venue).length,n,venue+' new bill count');
assert(added.every(e=>e.category==='Music'&&e.eventFormat==='live'));
assert(!added.some(e=>/Star Machine|Early Worms/i.test(e.title)),'No Fun Nov 13 conflicts held back');
assert(added.every(e=>e.url.startsWith('https://')&&e.sources.some(s=>s.url===e.url&&s.kind==='organizer')));
assert(added.every(e=>e.age==='21+'||e.age==='All ages'||e.age==='Not published'));
assert(added.every(e=>e.startsAt.slice(0,10)>='2026-10-18'&&e.startsAt.slice(0,10)<='2026-12-13'));
assert(added.every(e=>e.startsAt.endsWith(e.startsAt<'2026-11-01'?'-07:00':'-08:00')));
assert(added.every(e=>Array.isArray(e.musicStyles)&&(!e.musicStyles.length||e.musicStyleEvidence?.basis)));
assert(added.some(e=>e.musicStyles.length===0),'Unverified genres remain unclassified, not guessed');
assert(added.filter(e=>e.title.includes('tribute')||e.subtitle.includes('Tribute')).length>=1,'Clearly marked tribute shows');
assert(events.filter(e=>e.addedIn==='2026-10-17-venue-coverage').length===36,'Major venue expansion intact');
const app=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'..','styles.css'),'utf8');
assert(app.includes('function artMarkup('),'Central artwork renderer');
assert(app.includes("artMarkup(e,true)"),'Detail view artwork');
assert(app.includes("artMarkup(e)"),'List cards artwork');
assert(app.includes("arts.usageApproved===true"),'Flyer artwork opt-in only');
assert(css.includes('.show-art--goth')&&css.includes('.show-art--metal'),'Independent fallback palettes');
console.log('PASS — 27 independent venue bills, unknown genre policy, preserved batches and accessible editorial thumbnail hooks.');
